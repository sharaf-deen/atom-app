const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const page=fs.readFileSync('src/app/members/[id]/subscriptions/page.tsx','utf8')
const detail=fs.readFileSync('src/app/members/[id]/page.tsx','utf8')
const profile=fs.readFileSync('src/app/profile/page.tsx','utf8')

test('Dedicated member subscription page links from both profile and admin member detail',()=>{
 assert.match(page,/Membership & subscription history/)
 assert.match(detail,/Current &amp; full history/)
 assert.match(detail,/!coachSafeView/)
 assert.match(profile,/My membership &amp; subscription history/)
 assert.match(profile,/encodeURIComponent\(me\.id\)/)
})
test('Access restricted to self or reception/admin/super_admin before privileged reads',()=>{
 assert.match(page,/const staff=\['reception','admin','super_admin'\]\.includes\(me\.role\)/)
 assert.match(page,/const isSelf=UUID\.test\(params\.id\)&&me\.id===params\.id/)
 assert.match(page,/if\(!staff&&!isSelf\)return/)
 assert.match(page,/const db=staff\?createSupabaseAdminClient\(\):createSupabaseRSC\(\)/)
 assert.match(page,/if\(!staff&&member\.user_id!==me\.id\)return notFound\(\)/)
 assert.doesNotMatch(page,/\.(insert|update|delete|upsert|rpc)\(/)
})
test('Current membership checks status and valid date, includes frozen plans and sessions balance',()=>{
 assert.match(page,/if\(row\.status!=='active'\) return false/)
 assert.match(page,/row\.start_date>today/)
 assert.match(page,/row\.remaining_classes\?\?/)
 assert.match(page,/return !!row\.end_date&&row\.end_date>=today/)
 assert.match(page,/status==='Frozen'/)
 assert.match(page,/No currently valid subscription recorded/)
})
test('History is full server-side paginated, excludes current IDs and does not fabricate cash paid',()=>{
 assert.match(page,/select\(SELECT,\{count:'exact'\}\)/)
 assert.match(page,/not\('id','in'/)
 assert.match(page,/\.range\(\(page-1\)\*PER_PAGE,page\*PER_PAGE-1\)/)
 assert.match(page,/const PER_PAGE=20/)
 assert.match(page,/Payment method on record/)
 assert.match(page,/Recorded subscription amount/)
 assert.match(page,/Outstanding amount/)
 assert.match(page,/not a complete payment ledger/)
 assert.match(page,/This page is read-only/)
})
