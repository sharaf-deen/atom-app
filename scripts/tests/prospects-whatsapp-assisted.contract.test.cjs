const test = require('node:test')
const assert = require('node:assert/strict')
const fs=require('node:fs')
const read=(p)=>fs.readFileSync(p,'utf8')
const route=read('src/app/api/admin/prospects/route.ts')
const ui=read('src/components/admin/ProspectMessageComposer.tsx')
const sql=read('supabase/migrations/20261109190000_crm_whatsapp_assisted_followup.sql')
test('manual confirmation only; no WhatsApp API outbound',()=>{
 assert.match(route,/body\?\.confirmed !== true/)
 assert.match(ui,/I confirm I actually sent/)
 assert.match(ui,/no automatic sending/)
 assert.match(sql,/delivery_unverified/)
 assert.doesNotMatch(route,/graph\.facebook\.com|messages\.send|api\.whatsapp\.com/)
})
test('server atomic followup and audit plus restricted execution',()=>{
 assert.match(sql,/for update/)
 assert.match(sql,/next_follow_up_at=p_follow_up_at/)
 assert.match(sql,/public\.prospect_activities/)
 assert.match(sql,/grant execute on function public\.crm_confirm_prospect_whatsapp_sent_v1/)
 assert.match(sql,/to service_role/)
 assert.match(sql,/PROSPECT_ALREADY_CLOSED/)
})
test('French editable templates and assisted CRM',()=>{
 assert.match(sql,/language in \('en','ar','fr'\)/)
 assert.match(ui,/<option value="fr">Français<\/option>/)
 assert.match(ui,/onConfirmSent/)
})
