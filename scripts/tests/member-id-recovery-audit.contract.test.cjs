const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const read=p=>fs.readFileSync(p,'utf8')
const schema=read('supabase/migrations/20261115090000_member_id_gap_recovery_workflow.sql')
const cron=read('supabase/migrations/20261115091000_member_id_gap_daily_scan.sql')
const api=read('src/app/api/admin/members/member-id-recovery/route.ts')
const ui=read('src/app/admin/members/member-id-recovery/MemberIdRecoveryPanel.tsx')
const page=read('src/app/admin/members/member-id-recovery/page.tsx')
const members=read('src/app/admin/members/page.tsx')

test('legacy historical usage blocks reissue and clean gaps require Super Admin attestation',()=>{
  assert.match(schema,/historical_do_not_reissue/)
  assert.match(schema,/manual_review/)
  assert.match(schema,/member_id_gap_evidence/)
  assert.match(schema,/audit_logs/)
  assert.match(schema,/scan_audit/)
  assert.match(schema,/store_sales/)
  assert.match(schema,/coach_member_incidents/)
  assert.match(schema,/member_id_deletion_events/)
  assert.match(schema,/p_attested is distinct from true/)
  assert.match(schema,/HISTORICAL_EVIDENCE_BLOCKS_REISSUE/)
  assert.match(schema,/REVIEW_ATTESTATION_AND_UNIQUE_IDS_REQUIRED/)
  assert.match(api,/body.attested!==true/)
  assert.match(ui,/independently confirm the number was never used/)
})

test('automated detection logs every deletion but does not approve gaps',()=>{
  assert.match(schema,/after delete on public.profiles for each row/)
  assert.match(schema,/create or replace function public.member_id_gap_scan_system/)
  assert.match(cron,/0 3 \* \* \*/)
  assert.match(cron,/select public.member_id_gap_scan_system\(\)/)
  assert.doesNotMatch(cron,/member_id_approve_gaps|delete from public.profiles/i)
  assert.match(page,/member_id_gap_scan/)
  assert.match(schema,/classification='no_longer_missing'/)
})

test('future mistaken registrations require restricted reviewed deletion with no dependencies',()=>{
  assert.match(schema,/create or replace function public.member_id_release_archived_error/)
  assert.match(schema,/SUPER_ADMIN_REQUIRED/)
  assert.match(schema,/CREATED_IN_ERROR:%/)
  assert.match(schema,/AUTH_OR_FAMILY|NOT_SAFE_ARCHIVED_ERROR/)
  assert.match(schema,/pg_catalog.pg_constraint/)
  assert.match(schema,/DEPENDENCY_BLOCKED/)
  assert.match(schema,/TEXTUAL_OR_HISTORICAL_EVIDENCE_BLOCKED/)
  assert.match(schema,/delete from public.profiles/)
  assert.match(schema,/insert into public.member_id_reissue_queue/)
  assert.match(schema,/alter column original_profile_user_id drop not null/)
})

test('legacy 593/595 FIFO preserved, no sequence reset and direct client writes restricted',()=>{
  assert.match(schema,/order by q.released_at,q.member_id/)
  assert.match(schema,/new.member_id:=coalesce\(v_reissued,public.generate_member_id\(\)\)/)
  assert.doesNotMatch(schema,/setval\(/i)
  assert.match(schema,/revoke insert, update, delete on public.member_id_reissue_queue/)
  assert.match(schema,/revoke all on function public.member_id_approve_gaps/)
  assert.match(schema,/grant execute on function public.member_id_gap_scan\(uuid\) to service_role/)
  assert.match(api,/normalizeRole\(actor\?\.role\)!=='super_admin'/)
  assert.match(page,/user.role!=='super_admin'/)
  assert.match(members,/href="\/admin\/members\/member-id-recovery"/)
})
