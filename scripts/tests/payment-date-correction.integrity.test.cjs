const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')
const sql = read('supabase/migrations/20261123193703_subscription_payment_date_correction_integrity.sql')
const route = read('src/app/api/admin/payments/[id]/payment-date/route.ts')
const ui = read('src/components/SubscriptionPaymentMethodCorrection.tsx')
const oldUi = read('src/components/EditPaymentDateButton.tsx')

test('date correction is a single atomic ledger, subscription and audit RPC', () => {
  assert.match(sql, /create or replace function public\.correct_subscription_payment_date_v1/)
  assert.match(sql, /where id = p_payment_id for update/)
  assert.match(sql, /where id = v_payment\.subscription_id for update/)
  assert.match(sql, /update public\.subscription_payments set paid_at = p_new_paid_at/)
  assert.match(sql, /select max\(coalesce\(p\.paid_at, p\.created_at\)\)/)
  assert.match(sql, /update public\.subscriptions set paid_at = v_latest/)
  assert.match(sql, /insert into public\.subscription_payment_date_corrections/)
})
test('super admin privilege and immutable audit storage', () => {
  assert.match(route, /normalizeRole\(profile\?\.role\) !== 'super_admin'/)
  assert.match(sql, /public\.is_super_admin\(p_actor\)/)
  assert.match(sql, /revoke all on function public\.correct_subscription_payment_date_v1/)
  assert.match(sql, /to service_role/)
  assert.match(sql, /enable row level security/)
  assert.match(sql, /grant select, insert on public\.subscription_payment_date_corrections to service_role/)
})
test('financial locks include validation, two generations of bank matches and refunds', () => {
  for(const name of ['payment_validation_batch_items', 'payment_validation_batches',
    'reconciliation_bank_matches', 'bank_payment_matches', 'membership_refunds']) {
    assert.ok(sql.includes(name), name)
  }
  assert.match(sql, /PAYMENT_VALIDATION_LOCKED/)
  assert.match(sql, /BANK_MATCH_LOCKED/)
  assert.match(sql, /REFUND_WORKFLOW_LOCKED/)
  assert.doesNotMatch(sql, /update public\.payment_validation_batches/)
})
test('stale write, no-op, future date and mandatory reason are guarded', () => {
  assert.match(sql, /is distinct from p_expected_paid_at/)
  assert.match(sql, /PAYMENT_DATE_UNCHANGED/)
  assert.match(sql, /FUTURE_PAYMENT_DATE/)
  assert.match(route, /validDateOnly\(date\)/)
  assert.match(route, /reason\.length < 5/)
  assert.match(route, /reason\.length > 500/)
  assert.match(route, /p_expected_paid_at: expected/)
})
test('both user interfaces use the guarded date route and ask for evidence', () => {
  assert.match(ui, /Correct payment/)
  assert.match(ui, /Payment date/)
  assert.match(ui, /expected_paid_at: selected\.paid_at/)
  assert.match(ui, /reason: reason\.trim\(\)/)
  assert.match(oldUi, /expected_paid_at: currentPaidAt/)
  assert.match(oldUi, /reason: reason\.trim\(\)/)
  assert.doesNotMatch(route, /\.update\(\{ paid_at:/)
})

test('audit corrections are append-only and cannot be edited or deleted', () => {
  const guard = read('supabase/migrations/20261123194038_subscription_payment_date_audit_append_only.sql')
  assert.match(guard, /before update or delete on public\.subscription_payment_date_corrections/)
  assert.match(guard, /PAYMENT_DATE_AUDIT_APPEND_ONLY/)
})

test('closed daily and cash validation periods block moving a payment in or out', () => {
  const guard = read('supabase/migrations/20261123194834_subscription_payment_date_validated_period_guard.sql')
  assert.match(guard, /PAYMENT_DATE_VALIDATED_PERIOD_LOCKED/)
  assert.match(guard, /b\.validation_mode = 'daily'/)
  assert.match(guard, /b\.validation_mode = 'cash_period'/)
  assert.match(guard, /b\.business_date in/)
  assert.match(guard, /b\.period_from/)
  assert.match(guard, /b\.period_to/)
  assert.match(guard, /b\.deleted_at is null/)
  assert.match(guard, /b\.payment_method = public\.normalize_payment_method\(v_payment\.payment_method\)/)
})
