const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const sql=fs.readFileSync('supabase/migrations/20261115070000_member_000595_controlled_reissue.sql','utf8')

test('only ATOM-000595 is eligible for reissue',()=>{
 assert.match(sql,/member_id_reissue_single_target check \(member_id='ATOM-000595'\)/)
 assert.match(sql,/where member_id='ATOM-000595'/)
 assert.match(sql,/v_record\.user_id <> 'edc76e9e-d382-46cc-87b3-05cbda1e660f'/)
 assert.match(sql,/ARCHIVED_DUPLICATE/)
 assert.match(sql,/ORIGINAL_RECOVERY_AUDIT_MISSING/)
})
test('release requires super admin and proves absence of dependencies',()=>{
 assert.match(sql,/role='super_admin'/)
 assert.match(sql,/where id=v_record\.user_id/)
 assert.match(sql,/family_members/)
 assert.match(sql,/family_guardians/)
 assert.match(sql,/pg_catalog\.pg_constraint/)
 assert.match(sql,/DEPENDENCY_BLOCKED/)
 assert.match(sql,/delete from public\.profiles/)
 assert.match(sql,/ALREADY_RELEASED/)
 assert.match(sql,/revoke all on function public\.release_erroneous_atom_000595/)
 assert.match(sql,/to service_role/)
})
test('next genuine member consumes released number exactly once and leaves the normal sequence intact',()=>{
 assert.match(sql,/TG_OP='INSERT' and NEW\.role='member' and NEW\.archived_at is null/)
 assert.match(sql,/for update of q/)
 assert.match(sql,/consumed_by_profile_user_id=NEW\.user_id/)
 assert.match(sql,/NEW\.member_id:=coalesce\(v_reissued,public\.generate_member_id\(\)\)/)
 assert.doesNotMatch(sql,/setval\(/i)
 assert.doesNotMatch(sql,/delete from public\.family_duplicate_recovery_audit/)
})
