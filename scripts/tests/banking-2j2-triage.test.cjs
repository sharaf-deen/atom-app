const test = require('node:test')
const assert = require('node:assert/strict')
const {readFileSync} = require('node:fs')
const source = readFileSync('src/components/admin/banking/BankAssistedBulk2J.tsx','utf8')
test('2J.2 separates exhaustive InstaPay categories without financial writes', () => {
  assert.match(source, /type Triage = 'review' \| 'conflict' \| 'missing'/)
  assert.match(source, /!row\.options\.length \? 'missing'/)
  assert.match(source, /competing \|\| row\.options\.length > 1 \? 'conflict' : 'review'/)
  assert.match(source, /batchUsage\.set\(b\.id/)
  assert.match(source, /Reviewable batches/)
  assert.match(source, /Competing batches/)
  assert.match(source, /No validated batch/)
  assert.match(source, /visibleInstaPay\.map/)
  assert.match(source, /setTriage\(group\.key\)/)
})
test('2J.2 maintains explicit verification and full selection across tabs', () => {
  assert.match(source, /const selected = instant\.filter/)
  assert.match(source, /choices\[r\.credit\.id\]\?\.verified/)
  assert.match(source, /noDuplicates/)
  assert.match(source, /approved && noDuplicates/)
  assert.match(source, /pairs: selected\.map/)
  assert.doesNotMatch(source, /useEffect\(/)
})
