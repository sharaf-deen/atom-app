const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const read=p=>fs.readFileSync(p,'utf8')
const page=read('src/app/notifications/page.tsx')
const workspace=read('src/components/NotificationsWorkspace.tsx')
const list=read('src/components/NotificationsList.tsx')
const inbox=read('src/components/NotificationsMemberInbox.tsx')
const sent=read('src/app/api/notifications/sent/list/route.ts')
const deletion=read('src/app/api/notifications/delete/route.ts')
const clearRead=read('src/app/api/notifications/clear-read/route.ts')
const query=read('supabase/migrations/20261116140000_notifications_sent_groups_pagination.sql')

test('Simplified notification page mounts only the chosen admin tab',()=>{
 assert.match(page,/NotificationsWorkspace hasInbox=\{hasInbox\}/)
 assert.match(workspace,/tab==='inbox'&&hasInbox\?<NotificationsList isAdmin\/>/)
 assert.match(workspace,/tab==='sent'\?<NotificationsList isAdmin sentOnly\/>/)
 assert.match(workspace,/tab==='member'\?<NotificationsMemberInbox canDelete\/>/)
 assert.match(workspace,/tab==='compose'\?<NotificationsSender\/>/)
 assert.match(page,/initialThread=\{thread\}/)
})
test('Sent messages use server-paginated grouped query and no massive client fetch',()=>{
 assert.match(list,/const PER_PAGE = 8/)
 assert.match(list,/params\.set\('page', String\(p\)\)/)
 assert.match(list,/params\.set\('limit', String\(PER_PAGE\)\)/)
 assert.doesNotMatch(list,/params\.set\('limit', '1000'\)|ensureAudienceCounts\(|groupSent\(/)
 assert.match(sent,/atom_notifications_sent_groups/)
 assert.match(sent,/p_actor:me\.id/)
 assert.match(sent,/\['admin','super_admin','head_coach'\]/)
 assert.match(query,/limit p_limit offset \(p_page-1\)\*p_limit/)
 assert.match(query,/group by date_trunc\('second',n\.created_at\),n\.title,n\.body,n\.kind/)
 assert.match(query,/source_ids/)
})
test('Safe deletion remains individual soft deletion; broadcast groups use bounded requests',()=>{
 assert.match(deletion,/deleted_for_sender_at: now/)
 assert.match(deletion,/deleted_for_user_at: now/)
 assert.match(deletion,/\.eq\('created_by', auth\.user\.id\)/)
 assert.match(deletion,/\.eq\('user_id', auth\.user\.id\)/)
 assert.doesNotMatch(deletion,/\.delete\(/)
 assert.match(list,/offset\+=200/)
 assert.match(list,/deleteIds\(ids\.slice\(offset,offset\+200\),'sent'\)/)
 assert.match(inbox,/async function deleteSelected\(/)
 assert.match(list,/async function deleteSelected\(/)
})
test('SQL read protection and no underlying message modification',()=>{
 assert.match(query,/NOTIFICATION_SENDER_FORBIDDEN/)
 assert.match(query,/n\.created_by=p_actor/)
 assert.match(query,/n\.deleted_for_sender_at is null/)
 assert.match(query,/revoke all on function public\.atom_notifications_sent_groups/)
 assert.match(query,/grant execute on function public\.atom_notifications_sent_groups/)
 assert.doesNotMatch(query,/delete from public\.notifications/)
})

test('Read cleanup is explicitly confirmed, respects own user, and leaves unread/history intact',()=>{
 assert.match(list,/async function clearReadInbox\(\)/)
 assert.match(list,/Clear read messages/)
 assert.match(list,/confirm\('Remove all read notifications from your inbox/)
 assert.match(clearRead,/getSessionUser\(\)/)
 assert.match(clearRead,/p_actor:me\.id/)
 assert.match(clearRead,/atom_notifications_clear_read/)
 assert.match(query,/update public\.notifications\s+set deleted_for_user_at=now\(\)/)
 assert.match(query,/where user_id=p_actor and read_at is not null and deleted_for_user_at is null/)
 assert.match(query,/NOTIFICATION_ACTOR_FORBIDDEN/)
 assert.match(query,/revoke all on function public\.atom_notifications_clear_read/)
 assert.doesNotMatch(query,/delete from public\.notifications/)
})
