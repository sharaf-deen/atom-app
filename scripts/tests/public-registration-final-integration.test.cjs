// Single-lot static guardrail checks. Runtime email/Auth E2E is intentionally separate.
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = rel => fs.readFileSync(path.join(process.cwd(), rel), 'utf8')

test('public /registration displays real server-supplied programs and active required documents', () => {
  const p = read('src/app/registration/page.tsx')
  assert.match(p, /loadActiveMemberProgramOptions/)
  assert.match(p, /legal_document_versions/)
  assert.match(p, /\.eq\('status', 'active'\)/)
  assert.match(p, /ATOM_PUBLIC_REGISTRATION_SUBMIT_ENABLED/)
  assert.match(p, /ATOM_REGISTRATION_RATE_LIMIT_SECRET/)
  assert.match(p, /PublicRegistrationForm/)
})

test('every privileged transition checks feature flag, session, server-side Super Admin and explicit approval', () => {
  const r = read('src/app/api/admin/public-registration/provisioning/advance/route.ts')
  assert.match(r, /ATOM_REGISTRATION_FINAL_INTEGRATION_ENABLED/)
  assert.match(r, /client\.auth\.getUser\(\)/)
  assert.match(r, /normalizeRole\(actor\?\.role\) !== 'super_admin'/)
  assert.match(r, /body\.confirm !== true/)
  assert.match(r, /planRegistrationProvisioning/)
  assert.match(r, /auditRegistrationIdentity/)
  assert.match(r, /ATOM_REGISTRATION_AUTH_PROVISIONING_ENABLED/)
  assert.match(r, /ATOM_REGISTRATION_INVITATION_ENABLED/)
  assert.match(r, /ATOM_REGISTRATION_MEMBER_FAMILY_PROVISIONING_ENABLED/)
})

test('no automatic chaining and rejection is limited to unprovisioned requests', () => {
  const r = read('src/app/api/admin/public-registration/provisioning/advance/route.ts')
  assert.match(r, /record\.provisioning_claim_id \|\| record\.provisioned_auth_user_id/)
  assert.match(r, /\.in\('status', \['pending_verification', 'under_review'\]\)/)
  assert.match(r, /\.is\('provisioned_auth_user_id', null\)/)
  assert.match(r, /review_decision_by: session\.user\.id/)
  assert.match(r, /OUTCOME_UNCERTAIN_REVIEW_BEFORE_RETRY/)
  const ui = read('src/app/reception/registrations/RegistrationAdminActions.tsx')
  assert.match(ui, /I have reviewed the dossier/)
  assert.match(ui, /chosenAction === 'APPROVE'/)
  assert.match(ui, /Refresh server diagnosis/)
  assert.doesNotMatch(ui, /Promise\.all\(/)
})

test('family and adult public submissions never activate a membership', () => {
  const r = read('src/app/api/public-registration/submit/route.ts')
  assert.match(r, /atom_submit_public_registration_v1/)
  assert.doesNotMatch(r, /createUser\(/)
  assert.doesNotMatch(r, /createSubscription\(/)
  const ui = read('src/components/public-registration/PublicRegistrationForm.tsx')
  assert.match(ui, /guardian_name/)
  assert.match(ui, /accepted_document_version_ids/)
  assert.match(ui, /No member account or paid subscription/)
})
