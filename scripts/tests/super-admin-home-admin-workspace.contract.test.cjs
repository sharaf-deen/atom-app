const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const component = fs.readFileSync('src/components/home/SuperAdminPages.tsx', 'utf8')
const home = fs.readFileSync('src/app/page.tsx', 'utf8')
const walk = (dir) => fs.readdirSync(dir, {withFileTypes:true}).flatMap(entry => {
  const p = path.join(dir, entry.name)
  return entry.isDirectory() ? walk(p) : [p]
})
test('Super Admin workspace includes every navigable /admin page exactly once', () => {
  const expected = walk('src/app/admin')
    .filter(p => p.endsWith('/page.tsx') || p === 'src/app/admin/page.tsx')
    .map(p => '/'+p.slice('src/app/'.length).replace(/\/page\.tsx$/, ''))
    .filter(p => !p.includes('[')).sort()
  const actual = [...component.matchAll(/href: '(\/admin(?:\/[^']*)?)'/g)].map(m=>m[1]).sort()
  assert.deepEqual(actual, expected)
  assert.equal(new Set(actual).size, actual.length)
})
test('All admin links are grouped in one semantic accessible block', () => {
  assert.match(component, /aria-labelledby="admin-workspace-title"/)
  assert.match(component, /<details/)
  assert.match(component, /<nav aria-label=\{group.title\}/)
  assert.match(component, /focus-visible:ring/)
  assert.match(component, /open=\{index === 0\}/)
})
test('Super Admin keeps separate non-admin quick actions; other roles untouched', () => {
  const start = home.indexOf("if (user.role === 'super_admin') {")
  const end = home.indexOf("  return (", start+100)
  assert.ok(start > 0)
  const block = home.slice(start,home.indexOf('\n  return (\n    <main',start))
  assert.match(block, /<SuperAdminPages \/>/)
  assert.match(block, /<QuickActions/)
  assert.match(block, /<HomeMemberLookup/)
  const quick = block.slice(block.indexOf('items={['),block.indexOf(']}',block.indexOf('items={[')))
  assert.doesNotMatch(quick, /href: '\/admin/)
  assert.match(home, /if \(user.role === 'reception'\)/)
  assert.match(home, /\(user.role === 'admin' \|\| user.role === 'super_admin'\)/)
})
