const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const read=p=>fs.readFileSync(p,'utf8')
const sql=read('supabase/migrations/20261116090000_program_health_dashboard.sql')
const api=read('src/app/api/admin/program-health/route.ts')
const page=read('src/app/admin/program-health/page.tsx')
const ui=read('src/app/admin/program-health/ProgramHealthDashboard.tsx')
const nav=read('src/components/home/SuperAdminPages.tsx')
test('Program Health available in Super Admin workspace with strict page and POST auth',()=>{
 assert.match(nav,/href: '\/admin\/program-health'/)
 assert.match(page,/me\.role!=='super_admin'/)
 assert.match(api,/me\.role !== 'super_admin'/)
 assert.match(api,/INVALID_PROGRAM_SETTINGS/)
 assert.match(api,/atom_program_health_update/)
})
test('Dashboard shows counts, attendance and transparent cash estimates',()=>{
 for(const token of ['Current enrollments','Active subscriptions','Active member target','Visited · 30d','Attributed net payments','Management notes / actions','Manage members','Review schedule','View members']){
  assert.ok(ui.includes(token),token)
 }
 assert.match(sql,/member_program_enrollments/)
 assert.match(sql,/e\.is_current=true and e\.ended_at is null/)
 assert.match(sql,/p\.archived_at is null/)
 assert.match(sql,/public\.subscriptions/)
 assert.match(sql,/public\.attendance/)
 assert.match(sql,/public\.subscription_payments/)
 assert.match(sql,/public\.membership_refunds/)
 assert.match(sql,/nullif\(cm\.program_count,0\)/)
 assert.match(sql,/Not historical program-level accounting/)
})
test('Capacity configuration is audited, limited, and inaccessible to public roles',()=>{
 assert.match(sql,/atom_program_health_settings_audit/)
 assert.match(sql,/target_capacity between 1 and 500/)
 assert.match(sql,/warning_percent between 50 and 100/)
 assert.match(sql,/SUPER_ADMIN_REQUIRED/)
 assert.match(sql,/REVOKE|revoke all on function public\.atom_program_health_update/)
 assert.match(sql,/to service_role/)
 assert.match(sql,/enable row level security/)
 assert.match(sql,/program_health_snapshot/)
 assert.doesNotMatch(sql,/update public\.subscriptions|delete from public\.subscriptions|update public\.member_program_enrollments/)
})

test('Program Health 1B: compact expandable program rows, active-only target and PT exclusion',()=>{
 assert.match(ui,/\['kids-pt','adults-pt'\]\.includes\(p\.key\)/)
 assert.match(ui,/p\.active>=p\.target_capacity/)
 assert.match(ui,/p\.active\/p\.target_capacity/)
 assert.doesNotMatch(ui,/p\.enrolled>=p\.target_capacity|p\.enrolled\/p\.target_capacity/)
 assert.match(ui,/aria-expanded=\{isExpanded\}/)
 assert.match(ui,/aria-controls=\{'program-health-details-'\+p\.key\}/)
 assert.match(ui,/\{isExpanded&&<div id=/)
 assert.match(ui,/Enrolled/)
 assert.match(ui,/Active/)
 assert.match(ui,/Active target/)
 assert.match(ui,/\{membersOpen&&<div/)
 assert.match(ui,/filter\(p=>!\['kids-pt','adults-pt'\]\.includes\(p\.key\)\)/)
})
