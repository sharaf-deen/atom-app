const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const sql=fs.readFileSync('supabase/migrations/20261117170000_cib_card_review_approval.sql','utf8')
const api=fs.readFileSync('src/app/api/admin/banking/cib-card-approvals/route.ts','utf8')
const ui=fs.readFileSync('src/components/admin/banking/CibReviewApprovalPanel.tsx','utf8')
test('Super Admin authorization on every approval route',()=>{
  assert.match(api,/if \(me\.role!=='super_admin'\)/)
  assert.match(api,/export async function GET/)
  assert.match(api,/export async function POST/)
  assert.match(api,/export async function DELETE/)
})
test('Atomic DB approval prevents reuse and amount mismatch',()=>{
  assert.match(sql,/pg_advisory_xact_lock/)
  assert.match(sql,/cib_card_approvals_active_transaction_key/)
  assert.match(sql,/cib_card_approval_items_unique_source_active/)
  assert.match(sql,/WHERE released_at IS NULL/)
  assert.match(sql,/IF v_sum <> p_gross_cents/)
  assert.match(sql,/SOURCE_ALREADY_USED/)
  assert.match(sql,/SOURCE_NOT_ELIGIBLE/)
  assert.match(sql,/p_evidence_note/)
})
test('Approval ledger grants service_role only and retains release history',()=>{
  assert.match(sql,/ENABLE ROW LEVEL SECURITY/g)
  assert.match(sql,/REVOKE ALL ON FUNCTION public\.cib_card_approve/)
  assert.match(sql,/GRANT EXECUTE ON FUNCTION public\.cib_card_approve/)
  assert.match(sql,/UPDATE public\.cib_card_approval_items SET released_at=now/)
  assert.doesNotMatch(api,/\.insert\(|\.update\(|\.upsert\(|\.delete\(/)
})
test('Approval UI requires explicit evidence and no automatic approval',()=>{
  assert.match(ui,/evidence\.trim\(\)\.length>=12/)
  assert.match(ui,/Approve reviewed allocation/)
  assert.match(ui,/Confirm release/)
  assert.match(ui,/source_id\.slice\(0,8\)/)
  assert.doesNotMatch(ui,/cardnumber|card_number|cardNumber/)
})
